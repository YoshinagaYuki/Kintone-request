// 「市」で終わるキーを先に判定する(政令市の区名と23区の衝突対策)。
// 例:「千葉県千葉市中央区」→「中央区(23区=03)」ではなく「千葉市(043)」を優先。
// 同区分内では長い名称を優先。
const MUNICIPALITY_KEYS = Object.keys(MUNICIPALITY_AREA_CODES).sort((a, b) => {
  const aCity = a.endsWith("市") ? 1 : 0;
  const bCity = b.endsWith("市") ? 1 : 0;
  if (aCity !== bCity) return bCity - aCity;
  return b.length - a.length;
});
const PREFECTURE_KEYS = Object.keys(PREFECTURE_AREA_CODES);

/** 住所文字列から市区町村の代表市外局番候補を返す(最長一致の市区町村名) */
export function detectMunicipalityCodes(address?: string | null): string[] {
  if (!address) return [];
  for (const key of MUNICIPALITY_KEYS) {
    if (address.includes(key)) return MUNICIPALITY_AREA_CODES[key];
  }
  return [];
}

/** 住所文字列から都道府県の市外局番候補を返す(「都道府県」抜き表記も許容) */
export function detectPrefectureCodes(address?: string | null): string[] {
  if (!address) return [];
  for (const p of PREFECTURE_KEYS) {
    const short = p.replace(/[都道府県]$/, "");
    if (address.includes(p) || (short && address.includes(short))) {
      return PREFECTURE_AREA_CODES[p];
    }
  }
  return [];
}
